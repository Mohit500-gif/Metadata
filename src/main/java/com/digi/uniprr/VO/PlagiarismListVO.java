package com.digi.uniprr.VO;

public class PlagiarismListVO {
	
	private String journalTitle;
	private Integer plagcheckcount;
	private Integer checkmonth;
	private Integer checkyear;
	public String getJournalTitle() {
		return journalTitle;
	}
	public void setJournalTitle(String journalTitle) {
		this.journalTitle = journalTitle;
	}
	public Integer getPlagcheckcount() {
		return plagcheckcount;
	}
	public void setPlagcheckcount(Integer plagcheckcount) {
		this.plagcheckcount = plagcheckcount;
	}
	public Integer getCheckmonth() {
		return checkmonth;
	}
	public void setCheckmonth(Integer checkmonth) {
		this.checkmonth = checkmonth;
	}
	public Integer getCheckyear() {
		return checkyear;
	}
	public void setCheckyear(Integer checkyear) {
		this.checkyear = checkyear;
	}
	
	

}
